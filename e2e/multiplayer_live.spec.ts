import { test, expect } from '@playwright/test';

test.describe('Live Multiplayer Synchronization & Telemetry', () => {
  test('Host creates room and Guest connects with bidirectional sync', async ({ browser }) => {
    // 1. Create two isolated browser contexts (Host and Guest)
    const hostContext = await browser.newContext();
    const guestContext = await browser.newContext();

    const hostPage = await hostContext.newPage();
    const guestPage = await guestContext.newPage();

    hostPage.on('console', (msg) => console.log('[HOST CONSOLE]:', msg.text()));
    guestPage.on('console', (msg) => console.log('[GUEST CONSOLE]:', msg.text()));

    hostPage.on('pageerror', (err) => console.error('[HOST ERROR]:', err));
    guestPage.on('pageerror', (err) => console.error('[GUEST ERROR]:', err));

    // 2. Load Host and start game in slot1
    await hostPage.goto('/');
    await hostPage.waitForFunction(() => typeof (window as any).__START_GAME__ === 'function');
    await hostPage.evaluate(() => {
      (window as any).__START_GAME__('slot1');
    });

    // 3. Host calls hostGame() and waits for room code
    const roomCode = await hostPage.evaluate(async () => {
      const net = (window as any).networkActions;
      net.getState().setPlayerName('CommanderHost');
      await net.getState().hostGame();
      
      // Wait up to 10s for PeerJS to assign roomCode
      for (let i = 0; i < 100; i++) {
        const code = net.getState().roomCode;
        if (code && code.length >= 6) return code;
        await new Promise((r) => setTimeout(r, 100));
      }
      throw new Error('Host failed to obtain room code');
    });

    console.log('[LIVE TEST] Room Code generated by Host:', roomCode);
    expect(roomCode).toBeTruthy();
    expect(roomCode.length).toBeGreaterThanOrEqual(6);

    // 4. Load Guest page
    await guestPage.goto('/');
    await guestPage.waitForFunction(() => typeof (window as any).networkActions !== 'undefined');

    // 5. Guest joins using roomCode
    const connectionResult = await guestPage.evaluate(async (code) => {
      const net = (window as any).networkActions;
      net.getState().setPlayerName('ExplorerGuest');
      await net.getState().joinGame(code);

      // Wait up to 15s for connectionStatus to become 'connected'
      for (let i = 0; i < 150; i++) {
        const status = net.getState().connectionStatus;
        if (status === 'connected') return { success: true, status };
        await new Promise((r) => setTimeout(r, 100));
      }
      return { success: false, status: net.getState().connectionStatus };
    }, roomCode);

    console.log('[LIVE TEST] Guest connection result:', connectionResult);
    expect(connectionResult.success).toBe(true);
    expect(connectionResult.status).toBe('connected');

    // 6. Wait 3s for WebRTC channels, 30Hz ticker, and ping/pong
    await hostPage.waitForTimeout(3000);

    // 7. Verify Host side telemetry and peer state
    const hostTelemetry = await hostPage.evaluate(() => {
      const net = (window as any).networkActions.getState();
      const stats = (window as any).__DEBUG_STATS__ || {};
      return {
        connectionsCount: net.connections?.length || 0,
        unreliableCount: net.unreliableConnections?.length || 0,
        isHost: net.isHost,
        players: Object.keys(net.players || {}),
        bytesSent: stats.bytesSent || 0,
        bytesReceived: stats.bytesReceived || 0,
        packetStats: stats.packetStats,
      };
    });

    console.log('[LIVE TEST] Host Telemetry:', JSON.stringify(hostTelemetry, null, 2));
    expect(hostTelemetry.connectionsCount).toBeGreaterThanOrEqual(1);
    expect(hostTelemetry.unreliableCount).toBeGreaterThanOrEqual(1);
    expect(hostTelemetry.bytesSent).toBeGreaterThan(0);
    expect(hostTelemetry.bytesReceived).toBeGreaterThan(0);

    // 8. Verify Guest side telemetry and peer state
    const guestTelemetry = await guestPage.evaluate(() => {
      const net = (window as any).networkActions.getState();
      const stats = (window as any).__DEBUG_STATS__ || {};
      return {
        connectionsCount: net.connections?.length || 0,
        unreliableCount: net.unreliableConnections?.length || 0,
        isHost: net.isHost,
        players: Object.keys(net.players || {}),
        bytesSent: stats.bytesSent || 0,
        bytesReceived: stats.bytesReceived || 0,
        packetStats: stats.packetStats,
      };
    });

    console.log('[LIVE TEST] Guest Telemetry:', JSON.stringify(guestTelemetry, null, 2));
    expect(guestTelemetry.connectionsCount).toBeGreaterThanOrEqual(1);
    expect(guestTelemetry.unreliableCount).toBeGreaterThanOrEqual(1);
    expect(guestTelemetry.bytesSent).toBeGreaterThan(0);
    expect(guestTelemetry.bytesReceived).toBeGreaterThan(0);

    // 9. Verify continuous 30Hz positional streaming reaches Host
    const hostReceivedGuestPosition = await hostPage.evaluate(() => {
      const net = (window as any).networkActions.getState();
      for (const id in net.players) {
        const p = net.players[id];
        if (p.positionBuffer && p.positionBuffer.length > 0) {
          const latest = p.positionBuffer[p.positionBuffer.length - 1];
          return { received: true, id, x: latest.x, y: latest.y, z: latest.z, bufferSize: p.positionBuffer.length };
        }
      }
      return { received: false };
    });

    console.log('[LIVE TEST] Host received Guest live streaming position:', hostReceivedGuestPosition);
    expect(hostReceivedGuestPosition.received).toBe(true);
    expect((hostReceivedGuestPosition as any).bufferSize).toBeGreaterThan(0);

    // 10. Verify bidirectional chat synchronization
    await hostPage.evaluate(() => {
      const net = (window as any).networkActions.getState();
      net.broadcastChatMessage('All systems operational in orbit.');
    });

    await guestPage.waitForTimeout(1000);

    const guestReceivedChat = await guestPage.evaluate(() => {
      const net = (window as any).networkActions.getState();
      const messages = net.chatMessages || [];
      return messages.some((m: any) => m.text && m.text.includes('All systems operational in orbit'));
    });

    console.log('[LIVE TEST] Guest received chat message from Host:', guestReceivedChat);
    expect(guestReceivedChat).toBe(true);

    // Clean up contexts
    await hostContext.close();
    await guestContext.close();
  });
});
